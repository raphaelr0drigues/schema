function q(
  aula: number,
  n: number,
  page: number,
  topic: string,
  difficulty: Difficulty,
  kind: QuestionKind,
  prompt: string,
  answer: string,
  wrong: [string, string, string],
  explanation: string,
  ref?: Ref,
): Question {
  return {
    id: `fe2-${String(aula).padStart(2, "0")}-${String(n).padStart(2, "0")}`,
    familyId: `fe2-${aula}-${n}`,
    lesson: `Aula ${String(aula).padStart(2, "0")}`,
    page,
    topic,
    difficulty,
    kind,
    prompt,
    options: [answer, ...wrong],
    correct: 0,
    explanation,
    source: `Aula ${String(aula).padStart(2, "0")}, p. ${page}`,
    reference:
      references[ref ?? specificRefs[`${aula}-${n}`] ?? defaults[aula - 1]],
    origin: "Exercício complementar autoral",
  };
}

